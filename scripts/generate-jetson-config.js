const fs = require('fs');
const path = require('path');

const APPLICATION_DIR = path.join(__dirname, '../docs/Edge/NVIDIA_Jetson/Application');
const CONFIG_OUTPUT = path.join(__dirname, '../src/components/jetson/config.auto.js');

const CATEGORY_MAP = {
  'Computer_Vision': 'communityList_cv',
  'Generative_AI': 'communityList_gen',
  'Robotics': 'communityList_robot',
  'Developer_Tools': 'developerToolsList',
  'Multimodal_AI': 'multimodalList',
  'Physical_AI': 'physicalAIList',
  'Managed_Services': 'managedServicesList'
};

function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return null;
  
  try {
    const yamlText = match[1];
    const result = {};
    
    const lines = yamlText.split(/\r?\n/);
    let currentArray = null;
    let currentObj = null;
    
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i].trim();
      
      if (!line) continue;
      
      if (line.startsWith('- ')) {
        if (currentArray) {
          currentArray.push(line.slice(2).trim().replace(/^['"]|['"]$/g, ''));
        }
      } else if (line.includes(':')) {
        const colonIndex = line.indexOf(':');
        const key = line.slice(0, colonIndex).trim();
        let value = line.slice(colonIndex + 1).trim();
        
        if (value === '') {
          if (key === 'tags') {
            currentArray = [];
            result[key] = currentArray;
          } else if (key === 'last_update') {
            currentObj = {};
            result[key] = currentObj;
          } else {
            result[key] = '';
          }
        } else {
          value = value.replace(/^['"]|['"]$/g, '');
          if (key === 'date' || key === 'author') {
            if (!result.last_update) result.last_update = {};
            result.last_update[key] = value;
          } else {
            result[key] = value;
          }
          currentArray = null;
          currentObj = null;
        }
      }
    }
    
    return result;
  } catch (e) {
    console.error('Parse error:', e.message);
    return null;
  }
}

function extractFirstImage(content) {
  const patterns = [
    /<img[^>]+src=["'](https?:\/\/[^"'\s]+\.(?:jpg|jpeg|png|webp|gif))/i,
    /!\[.*?\]\((https?:\/\/[^)]+\.(?:jpg|jpeg|png|webp|gif))/i
  ];
  
  for (const pattern of patterns) {
    const match = content.match(pattern);
    if (match) {
      let url = match[1];
      return url.replace(/\s+/g, '');
    }
  }
  
  return null;
}

function scanDirectory(dir) {
  const projects = [];
  
  if (!fs.existsSync(dir)) {
    console.log(`⚠️  Directory not found: ${dir}`);
    return projects;
  }
  
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.md'));
  
  for (const file of files) {
    const filePath = path.join(dir, file);
    const content = fs.readFileSync(filePath, 'utf-8');
    const frontmatter = parseFrontmatter(content);
    
    if (frontmatter && frontmatter.title && frontmatter.slug) {
      let img = frontmatter.image || 'https://files.seeedstudio.com/wiki/wiki-platform/S-tempor.png';
      
      if (img === 'https://files.seeedstudio.com/wiki/wiki-platform/S-tempor.png') {
        const extractedImg = extractFirstImage(content);
        if (extractedImg) {
          img = extractedImg;
        }
      }
      
      projects.push({
        name: frontmatter.title,
        img: img,
        URL: `https://wiki.seeedstudio.com${frontmatter.slug}`,
        category: frontmatter.tags || [],
        lastUpdated: frontmatter.last_update?.date,
        author: frontmatter.last_update?.author
      });
    } else {
      console.log(`⚠️  Skipped ${file}: ${frontmatter ? 'missing title or slug' : 'no frontmatter'}`);
    }
  }
  
  return projects;
}

function generateConfig() {
  const config = {};
  
  for (const [dirName, configKey] of Object.entries(CATEGORY_MAP)) {
    const dirPath = path.join(APPLICATION_DIR, dirName);
    const projects = scanDirectory(dirPath);
    config[configKey] = projects;
    console.log(`📁 ${dirName}: ${projects.length} projects`);
  }
  
  return config;
}

function main() {
  console.log('🔍 Scanning Jetson Application docs...\n');
  
  const config = generateConfig();
  
  const output = `// Auto-generated by generate-jetson-config.js
// DO NOT EDIT MANUALLY - Run "npm run generate-jetson-config" to regenerate
// Generated at: ${new Date().toISOString()}

export const communityList_cv = ${JSON.stringify(config.communityList_cv || [], null, 2)}

export const communityList_gen = ${JSON.stringify(config.communityList_gen || [], null, 2)}

export const communityList_robot = ${JSON.stringify(config.communityList_robot || [], null, 2)}

export const developerToolsList = ${JSON.stringify(config.developerToolsList || [], null, 2)}

export const multimodalList = ${JSON.stringify(config.multimodalList || [], null, 2)}

export const physicalAIList = ${JSON.stringify(config.physicalAIList || [], null, 2)}

export const managedServicesList = ${JSON.stringify(config.managedServicesList || [], null, 2)}
`;
  
  fs.writeFileSync(CONFIG_OUTPUT, output);
  console.log(`\n✅ Generated jetson config: ${CONFIG_OUTPUT}`);
}

main();
